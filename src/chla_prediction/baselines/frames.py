"""Log10 Chl-a frames of the image baselines: gap filling and fixed-range scaling."""

from __future__ import annotations

import math

import torch

from chla_prediction.recipe import CHLA_RANGE

__all__ = ["LOG_CHLA_RANGE", "fill_gaps", "from_unit", "to_unit"]

LOG_CHLA_RANGE = (math.log10(CHLA_RANGE[0]), math.log10(CHLA_RANGE[1]))


def to_unit(values: torch.Tensor) -> torch.Tensor:
    """Map log10 Chl-a in ``LOG_CHLA_RANGE`` onto [0, 1]."""
    low, high = LOG_CHLA_RANGE
    return (values.clamp(low, high) - low) / (high - low)


def from_unit(values: torch.Tensor) -> torch.Tensor:
    low, high = LOG_CHLA_RANGE
    return values * (high - low) + low


def fill_gaps(frames: torch.Tensor, valid: torch.Tensor) -> torch.Tensor:
    """Give invalid pixels of ``frames`` ``[B, T, H, W]`` their frame's valid mean.

    Both published baselines assume gap-free fields. For pix2pix the fill is
    the same in the conditioning image and in the real output packing, so
    the discriminator cannot tell real from generated by the gaps alone.
    """
    valid = valid.to(frames.dtype)
    total = (frames * valid).sum(dim=(2, 3))
    count = valid.sum(dim=(2, 3))
    mean = torch.where(count > 0, total / count.clamp_min(1.0), torch.zeros_like(total))
    return torch.where(valid > 0, frames, mean[:, :, None, None])
